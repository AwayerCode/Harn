// Generate the compiled schema data from the sole authoritative Skill schemas.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	data := map[string]json.RawMessage{}
	files, err := filepath.Glob("../../skills/swe/references/artifact-schemas/*.json")
	must(err)
	if len(files) == 0 {
		panic("run from apps/swe-cli")
	}
	for _, f := range files {
		b, e := os.ReadFile(f)
		must(e)
		var value any
		must(json.Unmarshal(b, &value))
		name := filepath.Base(f)
		data[name[:len(name)-5]] = b
	}
	b, err := json.Marshal(data)
	must(err)
	source, err := format.Source([]byte("// Code generated by go generate; DO NOT EDIT.\npackage checks\nconst SchemaJSON = " + strconv.Quote(string(b)) + "\n"))
	must(err)
	must(os.WriteFile("internal/checks/schemas_gen.go", source, 0644))
	b, err = os.ReadFile("../../skills/swe/references/system-design/schema.json")
	must(err)
	source, err = format.Source([]byte("// Code generated by go generate; DO NOT EDIT.\npackage systemdesign\nconst SchemaJSON = " + strconv.Quote(string(b)) + "\n"))
	must(err)
	must(os.WriteFile("internal/systemdesign/schema_gen.go", source, 0644))
}
func must(err error) {
	if err != nil {
		panic(fmt.Sprint(err))
	}
}
