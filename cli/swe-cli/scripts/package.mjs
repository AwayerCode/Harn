import './build.mjs';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { inject } from 'postject';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json')));
if (process.versions.node !== pkg.engines.node) throw new Error(`Packaging requires Node ${pkg.engines.node}`);
const dist = path.join(root, 'dist');
const config = { main: path.join(dist, 'swe-cli.cjs'), output: path.join(dist, 'sea.blob'), disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false };
const configFile = path.join(dist, 'sea-config.json'); fs.writeFileSync(configFile, JSON.stringify(config));
execFileSync(process.execPath, ['--experimental-sea-config', configFile], { stdio: 'inherit' });
const name = `swe-cli_${process.platform}_${process.arch}${process.platform === 'win32' ? '.exe' : ''}`;
const target = path.join(dist, name); fs.copyFileSync(process.execPath, target); fs.chmodSync(target, 0o755);
if (process.platform === 'darwin') execFileSync('codesign', ['--remove-signature', target]);
await inject(target, 'NODE_SEA_BLOB', fs.readFileSync(config.output), { sentinelFuse: 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2', ...(process.platform === 'darwin' ? { machoSegmentName: 'NODE_SEA' } : {}) });
if (process.platform === 'darwin') execFileSync('codesign', ['--sign', '-', target]);
const digest = crypto.createHash('sha256').update(fs.readFileSync(target)).digest('hex');
fs.writeFileSync(path.join(dist, 'SHA256SUMS'), `${digest}  ${name}\n`);
console.log(target);
